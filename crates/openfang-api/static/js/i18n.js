  function translateText(text) {
    var trimmed = (text || '').trim();
    if (!trimmed) return text;
    var target = exactText[language][trimmed] || regexTranslate(trimmed);
    if (!target || target === trimmed) return text;
    return text.replace(trimmed, target);
  }

  function shouldSkipNode(node) {
    var current = node && node.parentNode;
    while (current && current !== document.body) {
      if (current.nodeType === 1) {
        var tag = current.tagName;
        if (tag === 'CODE' || tag === 'PRE' || tag === 'KBD' || tag === 'SAMP' || current.hasAttribute('data-no-i18n')) {
          return true;
        }
      }
      current = current.parentNode;
    }
    return false;
  }

  function translateElement(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      if (shouldSkipNode(root)) return;
      root.textContent = translateText(root.textContent);
      return;
    }
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    var node;
    while ((node = walker.nextNode())) {
      if (shouldSkipNode(node)) continue;
      node.textContent = translateText(node.textContent);
    }
    var attrNames = ['placeholder', 'title', 'aria-label'];
    var elements = root.querySelectorAll ? root.querySelectorAll('*') : [];
    Array.prototype.forEach.call(elements, function(el) {
      attrNames.forEach(function(name) {
        var value = el.getAttribute(name);
        if (value) el.setAttribute(name, translateText(value));
      });
    });
  }

  function applyTranslations() {
    document.documentElement.lang = language;
    document.title = t('app_title');
    translateElement(document.body);
  }

  function notify() {
    listeners.forEach(function(fn) { fn(language); });
    setTimeout(applyTranslations, 0);
    setTimeout(applyTranslations, 50);
  }

  function setLanguage(nextLanguage) {
    language = normalizeLocale(nextLanguage);
    notify();
    return language;
  }

  function init(configLanguage) {
    language = normalizeLocale(configLanguage || detectBrowserLocale());
    applyTranslations();
    if (!window.__openfang_i18n_observer && document.body) {
      window.__openfang_i18n_observer = new MutationObserver(function(mutations) {
        mutations.forEach(function(mutation) {
          Array.prototype.forEach.call(mutation.addedNodes || [], function(node) {
            translateElement(node);
          });
        });
      });
      window.__openfang_i18n_observer.observe(document.body, { childList: true, subtree: true });
    }
    return language;
  }

  function onChange(fn) {
    listeners.push(fn);
  }

  return {
    init: init,
    t: t,
    onChange: onChange,
    getLanguage: function() { return language; },
    setLanguage: setLanguage,
    normalizeLocale: normalizeLocale,
    detectBrowserLocale: detectBrowserLocale,
    applyTranslations: applyTranslations,
    translateText: translateText
  };
